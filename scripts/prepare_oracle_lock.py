"""Refresh runtime-only pins from the validated local V2 environment."""
from importlib.metadata import distribution
from pathlib import Path
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

roots = ['fastapi','starlette','uvicorn','motor','pymongo','pydantic','pydantic-settings',
         'httpx','argon2-cffi','PyJWT','pyotp','cryptography','python-multipart','pypdf',
         'setuptools','python-docx','openpyxl','PyMuPDF','olefile','tzdata',
         'psycopg','psycopg-binary','psycopg-pool','aiokafka']
pins = {}
pending = list(roots)
while pending:
    name = canonicalize_name(pending.pop())
    if name in pins:
        continue
    dist = distribution(name)
    pins[name] = dist.version
    for raw in dist.requires or []:
        requirement = Requirement(raw)
        if requirement.marker is None or requirement.marker.evaluate({'extra':''}):
            pending.append(requirement.name)
# Security updates verified against the official package index before this release.
pins.update({'certifi':'2026.10.23','pypdf':'6.21.4','setuptools':'84.1.0'})
content = '# Runtime only; generated by scripts/prepare_oracle_lock.py. No test/dev server extras.\n'
content += '\n'.join(f'{name}=={version}' for name, version in sorted(pins.items()))+'\n'
target = Path(__file__).resolve().parents[1]/'backend/requirements-production.txt'
target.write_bytes(content.encode('utf-8'))
print(f'Wrote {len(pins)} runtime pins; no environment values read.')
