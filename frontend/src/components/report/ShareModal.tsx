import {Button} from '@/components/ui/button';
import type React from 'react';
import { useState } from 'react';
import {Modal} from '../ui/Modal';
import {
  X,
  Mail,
  Linkedin,
  Share2,
  Copy,
  Check,
  ExternalLink,
  MessageSquare,
  Sparkles,
  Smartphone,
} from 'lucide-react';
import { toast } from 'sonner';
import type { NormalizedReport } from '../../utils/normalizeReport';
import { getGrade } from '../../utils/normalizeReport';

export interface ShareModalProps {
  isOpen: boolean;
  onClose: () => void;
  candidate: {
    id?: string;
    name: string;
    email: string;
  };
  assessment: {
    jobTitle: string;
    roundType?: string;
  };
  report: NormalizedReport;
}

export default function ShareModal({
  isOpen,
  onClose,
  candidate,
  assessment,
  report,
}: ShareModalProps) {
  const [copiedLink, setCopiedLink] = useState(false);
  const [copiedSummary, setCopiedSummary] = useState(false);

  if (!isOpen) return null;

  const round = report.meta.roundType || assessment.roundType || 'Interview';
  const score = report.overall.overallScore;
  const grade = getGrade(score);
  const comm = report.overall.communication?.overall_score ?? report.overall.communication?.overallScore ?? null;
  const conf = report.overall.confidenceScore;

  // Build current report URL
  const reportUrl = typeof window !== 'undefined'
    ? `${window.location.origin}${window.location.pathname}?candidate=${candidate.id || ''}`
    : '';

  // Clean, professional summary text
  const summaryText = [
    `🎯 Candidate Evaluation Summary: ${candidate.name}`,
    `Role: ${assessment.jobTitle} (${round} Round)`,
    score !== null ? `Overall Score: ${score}/100 (Grade ${grade.letter})` : null,
    comm !== null ? `Communication: ${Math.round(comm)}/100` : null,
    conf !== null ? `Confidence: ${Math.round(conf)}/100` : null,
    `Evaluated Questions: ${report.questions.length}`,
    reportUrl ? `Full Report Link: ${reportUrl}` : null,
    `Generated by PrimeHire & VILS AI Assessment Engine`,
  ]
    .filter(Boolean)
    .join('\n');

  const emailSubject = `Candidate Evaluation Report: ${candidate.name} - ${assessment.jobTitle}`;
  const emailBody = `Hi Team,\n\nPlease find the interview evaluation summary for ${candidate.name}:\n\n` +
    `• Candidate: ${candidate.name} (${candidate.email})\n` +
    `• Position: ${assessment.jobTitle}\n` +
    `• Round: ${round} Round\n` +
    (score !== null ? `• Overall Performance: ${score}/100 (Grade ${grade.letter})\n` : '') +
    (comm !== null ? `• Communication: ${Math.round(comm)}/100\n` : '') +
    (conf !== null ? `• Confidence: ${Math.round(conf)}/100\n` : '') +
    `\nView complete interactive breakdown & video responses here:\n${reportUrl}\n\n` +
    `Best regards,\nPrimeHire AI Assessment Platform`;

  // 1. Share via Gmail Web
  const handleShareGmail = () => {
    const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&su=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(emailBody)}`;
    window.open(gmailUrl, '_blank', 'noopener,noreferrer');
    toast.success('Opened Gmail compose window!');
  };

  // 2. Share via Default Email Client
  const handleShareEmail = () => {
    const mailto = `mailto:?subject=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(emailBody)}`;
    window.location.href = mailto;
    toast.success('Opened email client!');
  };

  // 3. Share via LinkedIn
  const handleShareLinkedIn = () => {
    // Copy summary so user can easily paste it into LinkedIn post or message
    try {
      navigator.clipboard.writeText(summaryText);
    } catch {
      /* ignore */
    }
    const liUrl = `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(reportUrl || window.location.href)}`;
    window.open(liUrl, '_blank', 'noopener,noreferrer');
    toast.success('Summary copied! Opening LinkedIn sharing dialog...');
  };

  // 4. Share via WhatsApp
  const handleShareWhatsApp = () => {
    const waUrl = `https://api.whatsapp.com/send?text=${encodeURIComponent(summaryText)}`;
    window.open(waUrl, '_blank', 'noopener,noreferrer');
    toast.success('Opening WhatsApp...');
  };

  // 5. Copy Full Summary
  const handleCopySummary = async () => {
    try {
      await navigator.clipboard.writeText(summaryText);
      setCopiedSummary(true);
      toast.success('Evaluation summary copied to clipboard!');
      setTimeout(() => setCopiedSummary(false), 2000);
    } catch {
      toast.error('Unable to copy to clipboard.');
    }
  };

  // 6. Copy Direct Link
  const handleCopyLink = async () => {
    try {
      await navigator.clipboard.writeText(reportUrl || window.location.href);
      setCopiedLink(true);
      toast.success('Report link copied to clipboard!');
      setTimeout(() => setCopiedLink(false), 2000);
    } catch {
      toast.error('Unable to copy link.');
    }
  };

  // 7. System / Mobile Share API (if supported)
  const canNativeShare = typeof navigator !== 'undefined' && !!navigator.share;
  const handleNativeShare = async () => {
    if (!navigator.share) return;
    try {
      await navigator.share({
        title: `PrimeHire Report: ${candidate.name}`,
        text: summaryText,
        url: reportUrl || window.location.href,
      });
      toast.success('Shared successfully!');
      onClose();
    } catch (err) {
      // User cancelled share
    }
  };

  return (
    <Modal onClose={onClose} labelledBy="share-modal-title" showClose={false} className="max-w-lg p-6">
          {/* Header */}
          <div className="flex items-start justify-between border-b border-border pb-4 dark:border-border">
            <div>
              <div className="flex items-center gap-1.5 text-xs font-bold uppercase tracking-wider text-accent dark:text-accent">
                <Share2 size={13} />
                Share Candidate Report
              </div>
              <h2 id="share-modal-title" className="mt-1 text-lg font-bold text-foreground dark:text-white">
                {candidate.name}
              </h2>
              <p className="text-xs text-muted-foreground dark:text-muted-foreground">
                {assessment.jobTitle} · {round} Round {score !== null ? `· ${score}/100 (Grade ${grade.letter})` : ''}
              </p>
            </div>
            <Button variant="ghost"
              type="button"
              onClick={onClose}
              className="rounded-full p-1.5 text-muted-foreground hover:bg-muted hover:text-muted-foreground dark:hover:bg-muted dark:hover:text-muted-foreground"
              aria-label="Close dialog"
            >
              <X size={18} />
            </Button>
          </div>

          {/* Quick Share Platforms */}
          <div className="mt-5 space-y-4">
            <p className="text-xs font-semibold text-foreground dark:text-muted-foreground">
              Select destination to share candidate report:
            </p>

            <div className="grid grid-cols-2 gap-2.5 sm:grid-cols-2">
              {/* Gmail Button */}
              <Button variant="ghost"
                type="button"
                onClick={handleShareGmail}
                className="flex items-center gap-3 rounded-xl border border-border bg-background/60 p-3 text-left transition-all hover:border-primary hover:bg-[var(--primary-soft)]/50 hover:shadow-xs dark:border-border dark:bg-card/60 dark:hover:border-primary"
              >
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-destructive text-destructive-foreground shadow-xs">
                  <Mail size={18} />
                </div>
                <div className="min-w-0">
                  <p className="text-xs font-bold text-foreground dark:text-white">Gmail</p>
                  <p className="truncate text-[0.6875rem] text-muted-foreground dark:text-muted-foreground">Compose in Gmail</p>
                </div>
              </Button>

              {/* LinkedIn Button */}
              <Button variant="ghost"
                type="button"
                onClick={handleShareLinkedIn}
                className="flex items-center gap-3 rounded-xl border border-border bg-background/60 p-3 text-left transition-all hover:border-primary hover:bg-[var(--primary-soft)]/50 hover:shadow-xs dark:border-border dark:bg-card/60 dark:hover:border-primary"
              >
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-[#0077b5] text-white shadow-xs">
                  <Linkedin size={18} />
                </div>
                <div className="min-w-0">
                  <p className="text-xs font-bold text-foreground dark:text-white">LinkedIn</p>
                  <p className="truncate text-[0.6875rem] text-muted-foreground dark:text-muted-foreground">Share or message</p>
                </div>
              </Button>

              {/* WhatsApp Button */}
              <Button variant="ghost"
                type="button"
                onClick={handleShareWhatsApp}
                className="flex items-center gap-3 rounded-xl border border-border bg-background/60 p-3 text-left transition-all hover:border-primary hover:bg-[var(--primary-soft)]/50 hover:shadow-xs dark:border-border dark:bg-card/60 dark:hover:border-primary"
              >
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-[#25D366] text-white shadow-xs">
                  <MessageSquare size={18} />
                </div>
                <div className="min-w-0">
                  <p className="text-xs font-bold text-foreground dark:text-white">WhatsApp</p>
                  <p className="truncate text-[0.6875rem] text-muted-foreground dark:text-muted-foreground">Send to chat/group</p>
                </div>
              </Button>

              {/* Default Mail Client */}
              <Button variant="ghost"
                type="button"
                onClick={handleShareEmail}
                className="flex items-center gap-3 rounded-xl border border-border bg-background/60 p-3 text-left transition-all hover:border-primary hover:bg-[var(--primary-soft)]/50 hover:shadow-xs dark:border-border dark:bg-card/60 dark:hover:border-primary"
              >
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-primary text-primary-foreground shadow-xs">
                  <ExternalLink size={18} />
                </div>
                <div className="min-w-0">
                  <p className="text-xs font-bold text-foreground dark:text-white">Default Email</p>
                  <p className="truncate text-[0.6875rem] text-muted-foreground dark:text-muted-foreground">Outlook / Apple Mail</p>
                </div>
              </Button>
            </div>

            {/* Native OS Share (if supported) */}
            {canNativeShare && (
              <Button variant="ghost"
                type="button"
                onClick={handleNativeShare}
                className="flex w-full items-center justify-center gap-2 rounded-xl border border-primary bg-[var(--primary-soft)] py-2.5 text-xs font-bold text-accent hover:bg-[var(--primary-soft)] transition-colors dark:border-primary dark:bg-[var(--primary-soft)] dark:text-accent"
              >
                <Smartphone size={14} />
                Open Native Share Menu (Slack, Teams, etc.)
              </Button>
            )}

            {/* Copy Actions */}
            <div className="mt-4 pt-3 border-t border-border dark:border-border space-y-2">
              <div className="flex items-center gap-2">
                <Button variant="ghost"
                  type="button"
                  onClick={handleCopySummary}
                  className="flex-1 inline-flex items-center justify-center gap-1.5 rounded-xl border border-border bg-card py-2 text-xs font-semibold text-foreground hover:bg-background dark:border-border dark:bg-card dark:text-foreground dark:hover:bg-muted"
                >
                  {copiedSummary ? <Check size={14} className="text-success" /> : <Sparkles size={14} className="text-accent" />}
                  {copiedSummary ? 'Summary Copied!' : 'Copy Formatted Summary'}
                </Button>

                <Button variant="ghost"
                  type="button"
                  onClick={handleCopyLink}
                  className="flex-1 inline-flex items-center justify-center gap-1.5 rounded-xl border border-border bg-card py-2 text-xs font-semibold text-foreground hover:bg-background dark:border-border dark:bg-card dark:text-foreground dark:hover:bg-muted"
                >
                  {copiedLink ? <Check size={14} className="text-success" /> : <Copy size={14} />}
                  {copiedLink ? 'Link Copied!' : 'Copy Direct Link'}
                </Button>
              </div>
            </div>
          </div>
    </Modal>
  );
}
